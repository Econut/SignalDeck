package com.macdmr.radio;

import org.junit.Test;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import static org.junit.Assert.*;

public class P8ProtocolTest {
    @Test public void literalStockSmsPushHasValidExistingFrameChecksum() {
        Frame f = P8Protocol.decodeHex("6836020090B800010510"); // literal x2.c fixture, not generated by our encoder
        assertEquals(0x36, f.cmd); assertEquals(2, f.rw); assertEquals(0, f.sr);
        assertEquals("Status: SMS received", P8Protocol.describe(f));
    }
    @Test public void versionQueryMatchesIndependentGoldenPacket() {
        assertArrayEquals(hex("6834010195B900010110"), P8Protocol.versionQuery().encode());
    }
    @Test public void analogPreservesP8FieldOrderAndRepeatedMonitor() {
        Frame f = P8Protocol.analog(145500000, 145500000, 1, 0, 3, 0, 0, 0, 0, 2, 9, 1);
        // 145500000 == 0x08ac2760, little endian. Last two bytes both monitor1, NOT generic relay2.
        assertArrayEquals(hex("6027AC086027AC080100030000000002090101"), f.body);
        assertEquals(0x23, f.cmd); assertEquals(28, f.encode().length);
    }
    @Test public void versionIsTextAndNotSyntheticInteger() {
        Frame f = new Frame(0x34, 0, 0, "DMR003BN.UV.V026\0\r\n".getBytes(StandardCharsets.US_ASCII));
        assertEquals("DMR003BN.UV.V026", P8Protocol.versionText(f));
    }
    @Test public void corruptedTruncatedOrCombinedFramesAreRejected() {
        for (String s : new String[] {"", "0", "GG", "6836020090B800010410", "6836020090B8000105", "6836020090B8000105106836020090B800010510"}) {
            try { P8Protocol.decodeHex(s); fail(s); } catch (IllegalArgumentException expected) { }
        }
    }
    @Test public void analogRejectsByteTruncationAndMistakenMHzInput() {
        for (int bad : new int[] {-1, 256}) {
            try { P8Protocol.analog(145500000, 145500000, bad, 0, 1, 0, 0, 0, 0, 2, 1, 2); fail(); }
            catch (IllegalArgumentException expected) { }
        }
        try { P8Protocol.analog(145, 145, 1, 0, 1, 0, 0, 0, 0, 2, 1, 2); fail(); }
        catch (IllegalArgumentException expected) { }
    }
    @Test public void stockPcmEnvelopeSurvivesEveryReadBoundary() {
        byte[] packet = new byte[167]; packet[0]=(byte)0xbb; packet[3]=(byte)0xa0; packet[166]=0x44;
        for (int i=0;i<160;i++) packet[6+i]=(byte)(i*17);
        for (int cut=1;cut<packet.length;cut++) {
            PcmFramer parser = new PcmFramer(); java.io.ByteArrayOutputStream pcm = new java.io.ByteArrayOutputStream();
            PcmFramer.Out out=(b,o,n)->pcm.write(b,o,n);
            parser.feed(Arrays.copyOfRange(packet,0,cut),cut,out);
            parser.feed(Arrays.copyOfRange(packet,cut,packet.length),packet.length-cut,out);
            assertArrayEquals(Arrays.copyOfRange(packet,6,166),pcm.toByteArray()); assertEquals(1,parser.frames);
        }
    }
    private static byte[] hex(String s) {
        byte[] b=new byte[s.length()/2]; for(int i=0;i<b.length;i++)b[i]=(byte)Integer.parseInt(s.substring(i*2,i*2+2),16); return b;
    }
}
